    public function run(): void
    {
        foreach (self::EXTRA_SPORTS as $name) {
            Sport::firstOrCreate(['name' => $name]);
        }

        $sportIds = Sport::pluck('id', 'name');

        foreach (self::LOCATIONS as $data) {
            $location = Location::firstOrCreate(
                ['name' => $data['name']],
                ['address' => $data['address'], 'lat' => $data['lat'], 'lng' => $data['lng']],
            );

            $ids = collect($data['sports'])
                ->map(fn ($name) => $sportIds[$name] ?? null)
                ->filter()
                ->all();

            if ($ids !== []) {
                $location->sports()->syncWithoutDetaching($ids);
            }
        }
    }
